import { readFile, stat } from "node:fs/promises";
import { dirname } from "node:path";
import { within } from "../files.mjs";
import { parseJunit } from "./junit.mjs";
import { parseLcov } from "./lcov.mjs";
export function numeric(value) {
  if (typeof value === "number" && Number.isFinite(value)) return value;
  if (
    typeof value === "string" &&
    value.trim() &&
    Number.isFinite(Number(value))
  )
    return Number(value);
  return undefined;
}
function flatten(data, prefix = "", metrics = Object.create(null)) {
  if (!data || typeof data !== "object") return metrics;
  for (const [key, value] of Object.entries(data)) {
    const path = prefix ? `${prefix}.${key}` : key;
    const number = numeric(value);
    if (number !== undefined) metrics[path] = number;
    else if (value && typeof value === "object") flatten(value, path, metrics);
  }
  return metrics;
}
async function existingAncestor(root, path) {
  try {
    await within(root, path);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    if (path === ".") throw error;
    await existingAncestor(root, dirname(path));
  }
}
async function stamp(root, filename) {
  try {
    const info = await stat(await within(root, filename), { bigint: true });
    if (!info.isFile()) throw new Error("Report must be a regular file");
    return `${info.ino}:${info.size}:${info.mtimeNs}:${info.ctimeNs}`;
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}
export async function prepareReport(root, check) {
  if (!check.report) return null;
  await existingAncestor(root, check.report);
  return stamp(root, check.report);
}
async function rawReport(root, check, previous, maxBytes) {
  const current = await stamp(root, check.report);
  if (!current) throw new Error(`Report was not generated: ${check.report}`);
  if (current === previous)
    throw new Error(
      `Report was not regenerated by this check: ${check.report}`,
    );
  const path = await within(root, check.report);
  if ((await stat(path)).size > maxBytes)
    throw new Error("Report size limit exceeded");
  const raw = await readFile(path, "utf8");
  if (Buffer.byteLength(raw) > maxBytes)
    throw new Error("Report size limit exceeded");
  return raw;
}
export async function readReport(root, check, previous, maxBytes) {
  if (!check.report) return { metrics: {}, violations: [] };
  const raw = await rawReport(root, check, previous, maxBytes);
  if (check.format === "text") return { metrics: {}, violations: [] };
  if (check.format === "lcov")
    return { metrics: parseLcov(raw), violations: [] };
  if (check.format === "junit") return junitResult(raw);
  const data = JSON.parse(raw);
  return {
    metrics: Object.assign(flatten(data), flatten(data?.metrics)),
    violations: [],
  };
}
function junitResult(raw) {
  const metrics = parseJunit(raw);
  const violations = [];
  if (!metrics.tests)
    violations.push({
      rule: "empty-tests",
      message: "JUnit report contains no tests",
    });
  if (metrics.tests && !metrics.passed && !metrics.failures)
    violations.push({
      rule: "empty-tests",
      message: "JUnit report contains only skipped tests",
    });
  if (metrics.failures)
    violations.push({
      rule: "test-failed",
      message: `JUnit report contains ${metrics.failures} failed tests`,
    });
  return { metrics, violations };
}
